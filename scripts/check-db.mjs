import {DatabaseSync} from 'node:sqlite';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const db=new DatabaseSync(':memory:');
const migration=readFileSync(new URL('../src-tauri/migrations/001_initial.sql',import.meta.url),'utf8');
const upgrade=readFileSync(new URL('../src-tauri/migrations/002_sessions.sql',import.meta.url),'utf8');
const legacy=new DatabaseSync(':memory:');
legacy.exec(migration);
legacy.prepare("INSERT INTO changes(optimization_id,previous_value,new_value,status) VALUES(?,?,?,'pending')").run('legacy.preference','original','new');
legacy.exec(upgrade);
assert.equal(legacy.prepare('SELECT previous_value FROM changes').get().previous_value,'original');
assert.equal(legacy.prepare('SELECT category FROM changes').get().category,'Efeitos visuais');
assert.equal(legacy.prepare('PRAGMA user_version').get().user_version,2);
legacy.close();
db.exec(migration);db.exec(migration);
assert.equal(db.prepare('PRAGMA user_version').get().user_version,1);
db.exec(upgrade);
assert.equal(db.prepare('PRAGMA user_version').get().user_version,2);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM fps_sessions').get().n,0);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM benchmark_runs').get().n,0);
assert.throws(()=>db.prepare("INSERT INTO fps_sessions(label,conditions,stream,source,stats,frames) VALUES('x','x','x','unknown','{}','[]')").run());
db.prepare("INSERT INTO fps_sessions(label,conditions,stream,source,stats,frames) VALUES(?,?,?,?,?,?)").run('capture','same scene','PID 1 / swapchain A','PresentMon CSV / MsBetweenPresents','{"average_fps":100}','[10,10]');
assert.equal(JSON.parse(db.prepare('SELECT stats FROM fps_sessions').get().stats).average_fps,100);
db.prepare("INSERT INTO changes(optimization_id,previous_value,new_value,status) VALUES(?,?,?,'pending')").run('visual.menu_animation','1','0');
assert.equal(db.prepare('SELECT status FROM changes').get().status,'pending');
db.prepare("UPDATE changes SET status='applied' WHERE id=1").run();
assert.equal(db.prepare('SELECT previous_value FROM changes').get().previous_value,'1');
db.prepare("UPDATE changes SET status='restored' WHERE id=1").run();
assert.equal(db.prepare('SELECT status FROM changes').get().status,'restored');
db.prepare('INSERT INTO settings(key,value) VALUES(?,?)').run('profile','SAFE');
assert.throws(()=>db.prepare('INSERT INTO settings(key,value) VALUES(?,?)').run('profile','ADVANCED'));
db.close();console.log('SQLite: migração idempotente, diário de intenção, histórico original e unicidade verificados. Não substitui testes de restauro Win32.');
