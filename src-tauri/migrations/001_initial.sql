PRAGMA journal_mode=WAL;
PRAGMA foreign_keys=ON;
CREATE TABLE IF NOT EXISTS changes(id INTEGER PRIMARY KEY, optimization_id TEXT NOT NULL, previous_value TEXT NOT NULL, new_value TEXT NOT NULL, status TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, error TEXT);
CREATE TABLE IF NOT EXISTS logs(id INTEGER PRIMARY KEY, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, operation TEXT NOT NULL, detail TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS benchmarks(id INTEGER PRIMARY KEY,created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,label TEXT NOT NULL,conditions TEXT NOT NULL,snapshot TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY,value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS profiles(id INTEGER PRIMARY KEY,name TEXT NOT NULL,executable TEXT NOT NULL,profile TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS snapshots(id INTEGER PRIMARY KEY,created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,kind TEXT NOT NULL,data TEXT NOT NULL);
PRAGMA user_version=1;
